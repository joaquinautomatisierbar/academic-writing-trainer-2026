export function validateQuestions(questions) {
  const errors = [];
  const ids = new Set();
  for (const question of questions) {
    if (!question?.id || ids.has(question.id)) errors.push(`duplicate or missing id: ${question?.id ?? 'unknown'}`);
    ids.add(question?.id);
    if (!question?.section) errors.push(`${question?.id}: missing section`);
    if (!question?.prompt?.trim()) errors.push(`${question?.id}: missing prompt`);
    if (!Array.isArray(question?.choices) || question.choices.length !== 4 || question.choices.some((choice) => !choice.trim())) {
      errors.push(`${question?.id}: invalid choices`);
    }
    if (!Number.isInteger(question?.correctIndex) || question.correctIndex < 0 || question.correctIndex > 3) {
      errors.push(`${question?.id}: invalid correctIndex`);
    }
    if (!question?.explanation?.trim()) errors.push(`${question?.id}: missing explanation`);
    if (!['brian', 'academic-review-after-brian-expiry'].includes(question?.answerBasis)) {
      errors.push(`${question?.id}: undisclosed answer basis`);
    }
  }
  return { valid: errors.length === 0, errors };
}
